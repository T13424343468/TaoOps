using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace TaoOps.Server.Waf;

/// <summary>生成产物包：http 级 conf 片段 + server 级 conf 片段 + Lua 检查入口 + 规则数据文件。同输入同输出（确定性）。</summary>
public sealed record WafConfigBundle(
    string NginxConf, string SiteConf, string AccessLua, string RulesJson);

/// <summary>
/// OpenResty 配置生成器：输入规则集，确定性输出 conf 片段与 Lua 规则文件。
/// 设计口径：规则是数据（rules.json），检查逻辑是代码（access.lua 固定模板）——
/// 改规则不动代码，热更新只换 rules.json（写活纪律，tao-code-standard 一.9）。
/// </summary>
public static class OpenRestyConfigGenerator
{
    private static readonly JsonSerializerOptions RuleJsonOpts = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        Converters = { new JsonStringEnumConverter() },
    };

    /// <summary>产物在站点侧的安装根目录（conf 里引用的相对路径基准）。</summary>
    public const string InstallRoot = "/etc/openresty/taoops-waf";

    /// <summary>生成完整产物包。同输入逐字节同输出：排序稳定、无时间戳、无随机序。</summary>
    public static WafConfigBundle Generate(WafRuleSet ruleSet)
    {
        var activeRules = ruleSet.Rules
            .Where(r => r.Enabled)
            .OrderByDescending(r => r.Priority)
            .ThenBy(r => r.Id, StringComparer.Ordinal)
            .ToList();

        var rulesJson = JsonSerializer.Serialize(activeRules, RuleJsonOpts);
        var accessLua = BuildAccessLua(ruleSet.Settings);
        var nginxConf = BuildNginxConf(ruleSet.Settings);
        var siteConf = BuildSiteConf();
        return new WafConfigBundle(nginxConf, siteConf, accessLua, rulesJson);
    }

    private static string BuildSiteConf()
    {
        // server 级片段：站点 server {} 块内 include，请求进入前先过 WAF 检查。
        return $$"""
                # Generated by TaoOps WAF manager. Include this file inside each site's server {} block.
                access_by_lua_file {{InstallRoot}}/lua/access.lua;
                """;
    }

    private static string BuildNginxConf(WafSettings settings)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by TaoOps WAF manager. Do not edit by hand; regenerate instead.");
        sb.AppendLine("# Include this file inside the http {} block.");
        sb.AppendLine($$"""
                        lua_package_path '{{InstallRoot}}/lua/?.lua;;';
                        init_by_lua_block {
                            TAOOPS_WAF_RULES_FILE = '{{InstallRoot}}/lua/rules.json'
                            TAOOPS_WAF_ENABLED = {{(settings.Enabled ? "true" : "false")}}
                        }
                        """);
        return sb.ToString();
    }

    private static string BuildAccessLua(WafSettings settings)
    {
        var denyStatus = settings.DenyStatusCode;
        // 检查逻辑固定模板：白名单短路 → 黑名单/正则/CC 拦截 → 其余放行。
        // 规则数据从 rules.json 读，mtime 变化自动重载（热更新友好，无需 reload nginx）。
        return $$"""
                -- Generated by TaoOps WAF manager. Do not edit by hand; regenerate instead.
                -- Data file: rules.json (same directory). Rule changes hot-reload by mtime check.
                local lfs_ok, lfs = pcall(require, "lfs")
                local json = require("cjson.safe")
                local ngx_re = require("ngx.re")

                local RULES_FILE = TAOOPS_WAF_RULES_FILE
                local WAF_ENABLED = TAOOPS_WAF_ENABLED
                local DENY_STATUS = {{denyStatus}}
                local RELOAD_CHECK_INTERVAL = 5  -- seconds between mtime checks

                local cache = { rules = nil, mtime = nil, last_check = 0 }

                local function load_rules()
                    local f = io.open(RULES_FILE, "r")
                    if not f then return {} end
                    local body = f:read("*a")
                    f:close()
                    local decoded = json.decode(body)
                    return decoded or {}
                end

                local function maybe_reload(now)
                    if not lfs_ok then return end
                    if now - cache.last_check < RELOAD_CHECK_INTERVAL then return end
                    cache.last_check = now
                    local attr = lfs.attributes(RULES_FILE)
                    local mtime = attr and attr.modification or 0
                    if cache.mtime ~= mtime then
                        cache.mtime = mtime
                        cache.rules = load_rules()
                    end
                end

                local function match_ip(rule, ip)
                    return rule.pattern == ip
                end

                local function match_cc(rule, now)
                    local dict = ngx.shared.taoops_waf_cc
                    if not dict then return false end
                    local key = "cc:" .. rule.id .. ":" .. ngx.var.remote_addr
                    local count, err = dict:incr(key, 1, 0, rule.windowSeconds or 60)
                    if err then return false end
                    return count > (rule.maxRequests or 0)
                end

                local function match_regex(rule)
                    if not ngx.var.request_uri and not ngx.var.http_user_agent then return false end
                    local subject = (ngx.var.request_uri or "") .. " " .. (ngx.var.http_user_agent or "")
                    local from = ngx_re.find(subject, rule.pattern, "jo")
                    return from ~= nil
                end

                -- access_by_lua_file executes this file as the handler directly;
                -- a returned closure would never be invoked (found in live-fire testing).
                do
                    if not WAF_ENABLED then return end
                    local now = ngx.time()
                    maybe_reload(now)
                    local rules = cache.rules or load_rules()
                    local ip = ngx.var.remote_addr or ""
                    for _, rule in ipairs(rules) do
                        local hit = false
                        if rule.category == "IpWhitelist" or rule.category == "IpBlacklist" then
                            hit = match_ip(rule, ip)
                        elseif rule.category == "CcRate" then
                            hit = match_cc(rule, now)
                        else
                            hit = match_regex(rule)
                        end
                        if hit then
                            if rule.action == "Allow" then return end
                            if rule.action == "Deny" then
                                ngx.log(ngx.ERR, 'TAOOPS_WAF {"event":"deny","rule_id":"' .. rule.id
                                  .. '","rule_name":"' .. (rule.name or "") .. '","ip":"' .. ip
                                  .. '","uri":"' .. (ngx.var.request_uri or "") .. '"}')
                                return ngx.exit(DENY_STATUS)
                            end
                            ngx.log(ngx.ERR, 'TAOOPS_WAF {"event":"log","rule_id":"' .. rule.id
                              .. '","rule_name":"' .. (rule.name or "") .. '","ip":"' .. ip
                              .. '","uri":"' .. (ngx.var.request_uri or "") .. '"}')
                        end
                    end
                end
                """;
    }
}
